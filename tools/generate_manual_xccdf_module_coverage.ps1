param(
  [string]$OutputPath
)

$ErrorActionPreference = 'Stop'
$repoRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
if (-not $OutputPath) {
  $OutputPath = Join-Path $repoRoot 'modules\stigs\MANUAL_XCCDF_MODULE_COVERAGE.md'
}
$resolvedOutput = [IO.Path]::GetFullPath($OutputPath)
if (-not $resolvedOutput.StartsWith($repoRoot, [StringComparison]::OrdinalIgnoreCase)) {
  throw "OutputPath must remain inside the repository: $resolvedOutput"
}

$benchmarks = [ordered]@{
  '8' = 'ansible/U_RHEL_8_V2R8_STIG_Ansible/rhel8STIG-ansible/roles/rhel8STIG/files/U_RHEL_8_STIG_V2R8_Manual-xccdf.xml'
  '9' = 'ansible/U_RHEL_9_V2R9_STIG_Ansible/rhel9STIG-ansible/roles/rhel9STIG/files/U_RHEL_9_STIG_V2R9_Manual-xccdf.xml'
  '10' = 'ansible/U_RHEL_10_V1R2_STIG/U_RHEL_10_V1R2_Manual_STIG/U_RHEL_10_STIG_V1R2_Manual-xccdf.xml'
}
$duplicateBenchmarks = @{
  '8' = 'ansible/U_RHEL_8_V2R8_STIG/U_RHEL_8_V2R8_Manual_STIG/U_RHEL_8_STIG_V2R8_Manual-xccdf.xml'
  '9' = 'ansible/U_RHEL_9_V2R9_STIG/U_RHEL_9_V2R9_Manual_STIG/U_RHEL_9_STIG_V2R9_Manual-xccdf.xml'
}

function Markdown([string]$Value) {
  return (($Value -replace '\|', '\|') -replace '\s+', ' ').Trim()
}

$moduleMap = @{}
foreach ($manifest in (Get-ChildItem -Path (Join-Path $repoRoot 'modules\stigs\manifests') -File -Filter '*.pp')) {
  $text = [IO.File]::ReadAllText($manifest.FullName)
  foreach ($match in [regex]::Matches($text, 'V-[0-9]+')) {
    $vId = $match.Value
    if (-not $moduleMap.ContainsKey($vId)) {
      $moduleMap[$vId] = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    }
    [void]$moduleMap[$vId].Add($manifest.Name)
  }
}

$results = [ordered]@{}
foreach ($os in $benchmarks.Keys) {
  $relativePath = $benchmarks[$os]
  $path = Join-Path $repoRoot $relativePath
  if (-not (Test-Path -LiteralPath $path)) { throw "Missing benchmark: $path" }
  $hash = (Get-FileHash -Algorithm SHA256 -LiteralPath $path).Hash
  if ($duplicateBenchmarks.ContainsKey($os)) {
    $duplicatePath = Join-Path $repoRoot $duplicateBenchmarks[$os]
    if (Test-Path -LiteralPath $duplicatePath) {
      $duplicateHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $duplicatePath).Hash
      if ($duplicateHash -ne $hash) { throw "Manual XCCDF copies differ for RHEL $os" }
    }
  }
  [xml]$document = [IO.File]::ReadAllText($path)
  $namespace = [Xml.XmlNamespaceManager]::new($document.NameTable)
  $namespace.AddNamespace('xccdf', $document.DocumentElement.NamespaceURI)
  $release = $document.SelectSingleNode('//xccdf:plain-text[@id="release-info"]', $namespace).InnerText.Trim()
  $rows = foreach ($group in @($document.SelectNodes('//xccdf:Group[xccdf:Rule]', $namespace))) {
    $vId = [string]$group.id
    $rule = $group.SelectSingleNode('xccdf:Rule', $namespace)
    $modules = if ($moduleMap.ContainsKey($vId)) { @($moduleMap[$vId] | Sort-Object) } else { @() }
    [pscustomobject]@{
      OS = "RHEL $os"
      V = $vId
      Number = [int]($vId -replace '^V-', '')
      Status = if ($modules.Count -gt 0) { 'covered' } else { 'not covered' }
      Requirement = $rule.SelectSingleNode('xccdf:title', $namespace).InnerText.Trim()
      Modules = if ($modules.Count -gt 0) { $modules -join '<br>' } else { 'none' }
    }
  }
  $results[$os] = [ordered]@{
    RelativePath = $relativePath
    Release = $release
    Hash = $hash
    Rows = @($rows | Sort-Object Number)
  }
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Manual XCCDF coverage by Puppet module')
$lines.Add('')
$lines.Add('Generated by `tools/generate_manual_xccdf_module_coverage.ps1`. A STIG is marked `covered` when its exact `V-` identifier appears in one or more files below `modules/stigs/manifests/`; the matching manifest filename is listed in the final column. `not covered` rows end with `none`. This is a traceability report and does not by itself prove that a manifest completely implements the requirement or that a deployed host is compliant.')
$lines.Add('')
$lines.Add('The standalone RHEL 8 and RHEL 9 manual-package XMLs are optional duplicates of the tracked Ansible-role copies. When present, the generator requires them to be byte-identical. Each release is listed once rather than duplicating every row.')
$lines.Add('')
$lines.Add('## Summary')
$lines.Add('')
$lines.Add('| OS | Manual XCCDF | Rules | Covered | Not covered | SHA-256 |')
$lines.Add('|---|---|---:|---:|---:|---|')
foreach ($os in $benchmarks.Keys) {
  $result = $results[$os]
  $covered = @($result.Rows | Where-Object Status -eq 'covered').Count
  $notCovered = $result.Rows.Count - $covered
  $lines.Add("| RHEL $os | ``$($result.RelativePath)`` ($($result.Release)) | $($result.Rows.Count) | $covered | $notCovered | ``$($result.Hash)`` |")
}
$lines.Add('')
$lines.Add('## Coverage tables')
$lines.Add('')
foreach ($os in $benchmarks.Keys) {
  $lines.Add("### RHEL $os")
  $lines.Add('')
  $lines.Add('| OS | V ID | Coverage | STIG requirement | Module |')
  $lines.Add('|---|---|---|---|---|')
  foreach ($row in $results[$os].Rows) {
    $lines.Add("| $($row.OS) | $($row.V) | $($row.Status) | $(Markdown $row.Requirement) | $($row.Modules) |")
  }
  $lines.Add('')
}

[IO.Directory]::CreateDirectory((Split-Path $resolvedOutput -Parent)) | Out-Null
[IO.File]::WriteAllText($resolvedOutput, (($lines -join "`n").TrimEnd() + "`n"), [Text.UTF8Encoding]::new($false))
Write-Output "Wrote $resolvedOutput."
